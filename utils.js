// 正規化キー → 正規名 のマップを構築
const INGREDIENT_ALIAS_MAP = {};
for (const group of INGREDIENT_ALIAS_GROUPS) {
  const canonical = group[0].toLowerCase();
  for (const variant of group) {
    INGREDIENT_ALIAS_MAP[variant.toLowerCase()] = canonical;
  }
}

// 材料名を正規化してマージ用キーを返す
// 辞書にあれば正規名、なければ小文字化・トリムした文字列をそのまま返す
export function normalizeIngredientKey(name) {
  const base = (name || '').toString().trim().toLowerCase();
  return INGREDIENT_ALIAS_MAP[base] || base;
}
