export function getShoppingCategory(name) {
  const lower = (name || '').toLowerCase();
  for (const group of SHOPPING_CATEGORY_KEYWORDS) {
    if (group.keywords.some(k => lower.includes(k.toLowerCase()))) {
      return group.category;
    }
  }
  return 'その他';
}

